def build(output: Path) -> Path:
    output = output.resolve()
    if output.exists():
        if not (output / MARKER).is_file():
            raise SystemExit(f"Refusing to replace unmarked directory: {output}")
        shutil.rmtree(output, onerror=remove_readonly)
    build_substrate(output)
    domain_root = output / "domain"
    build_product_studio(domain_root / "Product Studio")
    build_research_library(domain_root / "Research Library")
    build_service_operations(domain_root / "Service Operations")
    return output


def clean(output: Path) -> Path:
    output = output.resolve()
    if not output.exists():
        return output
    if not (output / MARKER).is_file():
        raise SystemExit(f"Refusing to remove unmarked directory: {output}")
    shutil.rmtree(output, onerror=remove_readonly)
    return output


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path, help="directory to create")
    parser.add_argument("--clean", action="store_true", help="remove a marked generated estate instead of rebuilding it")
    arguments = parser.parse_args()
    result = clean(arguments.output) if arguments.clean else build(arguments.output)
    print(result)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
