"""Build the fictional, public-safe estate used by the Explorer guides.

The generated estate is deliberately disposable.  It contains no source material
from the real MarkdownLLM estate and uses fixed commit dates for repeatable docs.
"""

from __future__ import annotations

import argparse
import os
import shutil
import stat
import subprocess
from pathlib import Path


MARKER = ".public-demo-estate"


def remove_readonly(function, path: str, _error) -> None:
    """Retry removal after clearing Git's occasional Windows read-only bit."""
    os.chmod(path, stat.S_IWRITE)
    function(path)


def write(root: Path, relative: str, content: str) -> None:
    target = root / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content.strip() + "\n", encoding="utf-8")


def git(root: Path, *arguments: str, when: str | None = None) -> None:
    environment = os.environ.copy()
    if when:
        environment["GIT_AUTHOR_DATE"] = when
        environment["GIT_COMMITTER_DATE"] = when
    subprocess.run(
        ["git", "-c", f"safe.directory={root}", *arguments],
        cwd=root,
        env=environment,
        check=True,
        capture_output=True,
        text=True,
    )


def initialise(root: Path) -> None:
    root.mkdir(parents=True, exist_ok=True)
    git(root, "init", "--initial-branch", "main")
    git(root, "config", "user.name", "Northstar Studio")
    git(root, "config", "user.email", "hello@northstar.example")


def commit(root: Path, message: str, when: str) -> None:
    git(root, "add", "--all")
    git(root, "commit", "--message", message, when=when)


def build_substrate(root: Path) -> None:
    initialise(root)
    write(root, MARKER, "Generated by explorer/tools/build_public_demo_estate.py")
